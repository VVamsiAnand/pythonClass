# B2.1: Comparison / Relational Operators

m = int(input("Enter m: "))
n = int(input("Enter n: "))

print("\nComparison Results:")
print("m == n :", m == n)
print("m != n :", m != n)
print("m > n  :", m > n)
print("m < n  :", m < n)
print("m >= n :", m >= n)
print("m <= n :", m <= n)

