# 1. Assignment Statement
num = 5      # Assignment

# Conditional Statement
if num > 0:  # Conditional
    print("Positive Number")

# Loop Statement
for i in range(1, 4):   # Loop
    print("Value:", i)   # Print Statement

# 2. Multi-line Statement using '\'
sum1 = 10 + 20 + \
       30 + 40
print("Sum using \\ =", sum1)

# Multi-line Statement using Parentheses
sum2 = (10 + 20 +
        30 + 40)
print("Sum using () =", sum2)

# 3. Multiple Statements in One Line
a = 5; b = 10; print("Sum =", a + b)

# output
#Positive Number
#Value: 1
#Value: 2
#Value: 3
#Sum using \ = 100
#Sum using () = 100
#Sum = 15
